// ─────────────────────────────────────────────────────────────────────────────
// Lab test catalogue — the bench investigations a facility can offer.
//
// Covers routine haematology and chemistry, the infections and neglected
// tropical diseases seen in South Sudan, outbreak confirmation, TB and HIV
// monitoring, and the drug levels the formulary's narrow-range medicines need.
// A facility turns off what it cannot run in Settings. Imaging stays in the
// catalogue's own list in facility-settings.ts.
//
// `basic` is what a health centre can usually run itself; `special` needs a
// hospital or reference laboratory. Every LOINC code here was checked against the
// NLM LOINC index on 2026-11-01; one is left out where no code clearly fits,
// because a wrong code is worse than none in an export.
//
// Names are load-bearing. `matchCriticalRule` and `resolveLabResultProfile` read
// them as free text, so "Hemoglobin Electrophoresis" would fire the haemoglobin
// critical rule and "Glucose-6-Phosphate" the glucose one. Hence "Hb
// Electrophoresis" and "G6PD Screen"; lab-test-catalog.test.ts holds this.
// ─────────────────────────────────────────────────────────────────────────────

